interface Row {
  f: string;
  p?: string;
  id: string;
  ru: string;
  en: string;
  cat: string;
  tr: string;
  te: string;
  tc?: string;
  m?: MountKind;
  fam?: string;
  vr?: string;
  ve?: string;
  cap?: number;
}

function expand(rows: Row[], defaults: Partial<CurationEntry> = {}): CurationEntry[] {
  return rows.map((r) => ({
    file: r.f,
    part: r.p ?? '0',
    id: r.id,
    ru: r.ru,
    en: r.en,
    category: r.cat,
    tagsRu: r.tr.split(',').map((t) => t.trim()),
    tagsEn: r.te.split(',').map((t) => t.trim()),
    toolClasses: r.tc ? r.tc.split(',') : [],
    mount: r.m ?? 'hex-plug',
    ...(r.fam ? { family: r.fam } : {}),
    ...(r.vr && r.ve ? { variant: { ru: r.vr, en: r.ve } } : {}),
    ...(r.cap ? { capacity: r.cap } : {}),
    ...defaults,
  }));
}

