/**
 * Hand-curated metadata for the distinct geometries found in the HSW sources: names, categories,
 * search tags, tool classes. Geometry itself, licence and provenance come from the files.
 *
 * `file` is relative to the HSW project dir; any member of a duplicate cluster identifies it (the
 * pipeline matches by geometry, so moving the representative to another file does not orphan an entry).
 * `part` is the object inside a multi-part 3MF/STEP file (see `bun run bank:ingest --report`).
 *
 * Orientation of source parts is guessed from geometry (plug end / largest flat face, see
 * mesh_tool.guess_orientation) unless `orient` is given; the refit holders are modelled in the wall
 * frame already and set it explicitly. Elements built from a guess carry `orientation.source = 'auto'`.
 */
import type { PrintNotes } from '../src/schema.ts';
import type { AnchorMode, Orientation } from '../src/node/meshTool.ts';

export type MountKind = 'hex-plug' | 'm3-screw' | 'clip' | 'none';

export interface CurationEntry {
  file: string;
  part: string;
  id: string;
  ru: string;
  en: string;
  category: string;
  tagsRu: string[];
  tagsEn: string[];
  toolClasses: string[];
  mount: MountKind;
  /** Elements of one design share a family; `variant` labels this one. */
  family?: string;
  variant?: { ru: string; en: string };
  /** Number of objects held (recogniser hint); dimension ranges are left out where unmeasured. */
  capacity?: number;
  orient?: Orientation;
  anchor?: AnchorMode;
  printNotes?: PrintNotes;
}

export interface SkipEntry {
  file: string;
  part: string;
  reason: string;
}

